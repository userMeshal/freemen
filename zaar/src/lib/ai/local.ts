const COLOR_WORDS: [RegExp, string][] = [
  [/أخضر|اخضر|نعناع/, "mint"], [/وردي|زهري|بينك/, "rose"], [/ذهبي|ذهب/, "gold"], [/أزرق|ازرق|سماوي/, "sky"],
  [/بنفسجي|موف/, "violet"], [/برتقالي|أحمر|احمر|مرجاني/, "coral"], [/أسود|اسود|داكن|غامق|ليلي|دارك/, "night"],
  [/ليموني|أصفر|اصفر|فسفوري/, "lime"], [/بيج|رملي|بني/, "sand"],
];

/** تعديلات بسيطة بالكلام بدون نموذج: الثيم، الألوان، الاسم، نسبة الأسعار، شريط الإعلان */
export function localEdit(current: Blueprint, instruction: string): Blueprint {
  const b: Blueprint = structuredClone(current);
  const done: string[] = [];
  const t = instruction;

  if (/ناعم|هادئ|هادي|زجاج/.test(t) && b.theme !== "soft") {
    b.theme = "soft";
    done.push("حوّلت التصميم إلى الثيم الناعم");
  } else if (/جريء|سينمائي|قوي|صارخ/.test(t) && b.theme !== "bold") {
    b.theme = "bold";
    done.push("حوّلت التصميم إلى الثيم الجريء");
  } else if (/(غي[ّ]?ر|بد[ّ]?ل).{0,12}(ثيم|تصميم|قالب)/.test(t)) {
    b.theme = b.theme === "bold" ? "soft" : "bold";
    done.push(`بدّلت الثيم إلى ${b.theme === "bold" ? "الجريء" : "الناعم"}`);
  }

  const color = COLOR_WORDS.find(([re]) => re.test(t));
  if (color && PALETTES[color[1]]) {
    b.palette = color[1];
    done.push(`غيّرت الألوان إلى ${PALETTES[color[1]].name}`);
  }

  const name = extractName(t);
  if (name) {
    b.marquee = b.marquee.map((m) => (m === b.name ? name : m));
    b.name = name;
    b.nameLatin = translit(name).toUpperCase().replace(/-/g, "").slice(0, 8);
    done.push(`غيّرت الاسم إلى «${name}»`);
  }

  const pct = t.match(/(ارفع|زود|زوّد|نز[ّ]?ل|خف[ّ]?ض|نقص).{0,20}?(\d{1,2})\s*[%٪]/);
  if (pct) {
    const up = /ارفع|زود|زوّد/.test(pct[1]);
    const f = 1 + ((up ? 1 : -1) * Number(pct[2])) / 100;
    b.products = b.products.map((p) => ({ ...p, price: Math.max(1, Math.round(p.price * f)), compareAtPrice: p.compareAtPrice ? Math.round(p.compareAtPrice * f) : null }));
    done.push(`${up ? "رفعت" : "نزّلت"} كل الأسعار ${pct[2]}%`);
  }

  const ann = t.match(/(?:شريط الإعلان|الإعلان|اعلان|إعلان)\s*[:：]\s*(.{4,90})/);
  if (ann) {
    b.announcement = ann[1].trim();
    done.push("حدّثت شريط الإعلان");
  }

  b.reply = done.length
    ? `تم — ${done.join("، ")}.`
    : "هذا التعديل أدقّ من اللي أقدر أسويه الآن بالكلام. تقدر تعدّل المنتجات والنصوص والأسعار من لوحة التحكم بعد ما تحفظ متجرك، أو جرّب تطلب: تغيير الثيم، اللون، الاسم، أو رفع وتنزيل الأسعار بنسبة.";
  return normalizeBlueprint(b);
}
