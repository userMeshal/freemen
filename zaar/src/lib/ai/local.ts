const hash = (s: string) => Array.from(s).reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7);

function pickVertical(idea: string): Vertical | null {
  const text = idea.toLowerCase();
  let best: Vertical | null = null;
  let bestScore = 0;
  for (const v of V) {
    const score = v.keys.reduce((s, k) => s + (text.includes(k) ? k.length : 0), 0);
    if (score > bestScore) {
      best = v;
      bestScore = score;
    }
  }
  return best;
}

/** يستخرج الاسم إن ذكره التاجر صراحة: «اسمه كذا» / «اسم المتجر كذا» / «سمّه كذا» */
export function extractName(text: string): string | null {
  const m = text.match(/(?:اسم(?:ه|ها)?(?:\s+المتجر)?|سم[ّ]?(?:ه|يه|ها)|باسم|يكون اسمه)\s*[:：]?\s*["«]?([^\s"»،,.]{2,20}(?:\s[^\s"»،,.]{2,12})?)["»]?/);
  if (!m) return null;
  const name = m[1].trim();
  return /^(متجر|المتجر|يكون|هو)$/.test(name) ? null : name;
}

const AR_TO_LATIN: Record<string, string> = {
  ا: "a", أ: "a", إ: "i", آ: "a", ب: "b", ت: "t", ث: "th", ج: "j", ح: "h", خ: "kh", د: "d", ذ: "th", ر: "r", ز: "z", س: "s", ش: "sh",
  ص: "s", ض: "d", ط: "t", ظ: "z", ع: "a", غ: "gh", ف: "f", ق: "q", ك: "k", ل: "l", م: "m", ن: "n", ه: "h", ة: "a", و: "o", ي: "i", ى: "a", ئ: "e", ؤ: "o",
};
export function translit(ar: string): string {
  return Array.from(ar.replace(/[ً-ْـ]/g, ""))
    .map((c) => AR_TO_LATIN[c] ?? (/[a-z0-9]/i.test(c) ? c : c === " " ? "-" : ""))
    .join("");
}

