def cesc(s):
    s = s.replace('[[', '\\u202A').replace(']]', '\\u202C')
    return s.replace('"', '\\"') if '\\"' not in s else s

lines = ['// GENERATED by tools/gen_arabic.py - edit that file, not this one.',
         '#include "Lang.h"', '', 'namespace wz {', '', 'static const LangPair kArabic[] = {']
seen = set()
for en, ar in PAIRS:
    if en in seen: sys.exit('DUPLICATE KEY: ' + en[:60])
    seen.add(en)
    lines.append('    {"%s",\n     "%s"},' % (en, cesc(ar)))
lines += ['};', '', 'const LangPair* arabicTable(size_t& count) {',
          '    count = sizeof(kArabic) / sizeof(kArabic[0]);', '    return kArabic;', '}', '', '} // namespace wz', '']
open(ROOT + '/src/core/LangArabic.cpp', 'w', encoding='utf-8').write('\n'.join(lines))

# Report user-visible source strings that still have no translation.
def visible(s):
    if not re.search(r'[A-Za-z]{3}', s): return False
    if re.fullmatch(r'[A-Za-z0-9_.:/%+\-]*', s) and not s[:1].isupper(): return False
    return True
missing = [s for s in SRC if visible(s) and s not in seen]
