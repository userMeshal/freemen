#!/usr/bin/env python3
"""Generates src/core/LangArabic.cpp from the translation list below.

Keys are the English source strings exactly as they appear in the C++ code.
A key may be given as a unique prefix of a long source string. The script
checks that every key exists in the sources, that every translation keeps the
same printf conversions in the same order, and reports untranslated strings.

Markers: [[ ... ]] wraps a fragment in LRE/PDF so numbers with signs, ranges
and Latin technical text keep left-to-right order inside an Arabic sentence.
"""
import glob, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = sorted(glob.glob(ROOT + '/src/ui/*.cpp')) + sorted(glob.glob(ROOT + '/src/platform/*.cpp')) + [ROOT + '/src/main.cpp'] + sorted(glob.glob(ROOT + '/src/core/*.cpp'))
LIT = re.compile(r'"((?:[^"\\\n]|\\.)*)"')

def source_strings():
    out = []
    for f in FILES:
        if f.endswith('LangArabic.cpp'): continue
        src = re.sub(r'"\s*\n\s*"', '', open(f, encoding='utf-8').read())
        for m in LIT.finditer(src):
            if m.group(1) not in out: out.append(m.group(1))
    return out

SRC = source_strings()
EXTRA = ['ms', 'deg', 'Hz']          # composed at runtime, not literal call sites
PAIRS = []

def T(key, ar, extra=False):
    if key not in SRC and not (extra or key in EXTRA):
        cands = [s for s in SRC if s.startswith(key)]
        if len(cands) != 1:
            sys.exit('KEY NOT FOUND or ambiguous (%d): %s' % (len(cands), key[:70]))
        key = cands[0]
    spec = lambda s: re.findall(r'%[-+ 0#]*\d*(?:\.\d+)?[dfsuxc%]', s)
    if spec(key) != spec(ar):
        sys.exit('FORMAT MISMATCH: %s\n  %s\n  %s' % (key[:70], spec(key), spec(ar)))
    PAIRS.append((key, ar))

